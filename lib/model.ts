// Token Radar model v2 ("radar-2 comps"): implied launch value calibrated on the
// snapshot's own live-token protocols, never on a hardcoded list of names.
//
// Idea: a protocol that already trades tells the market what a dollar of TVL is
// worth in its category. For every category we take the median market-cap / TVL
// ratio of the snapshot's live-token protocols in that category (at least 3
// comparables, else the global median), clamp it, and apply it to a pre-token
// protocol's TVL. Then three adjustments, all from the protocol's own record:
//   growth    — 7-day TVL change, clamped, pulls the value up or down;
//   maturity  — days since DefiLlama started tracking it, older is more proven;
//   chains    — each extra chain is wider distribution, worth a little more.
//   implied = tvl_usd x categoryMultiple x growthMult x maturityMult x chainMult
//
// A protocol is pre-token when its record carries no market cap, no CoinGecko id
// and no symbol. The board ranks every rankable pre-token protocol in the
// snapshot: the watchlist plus every other pre-token protocol that is not a
// wrapped, staked or bridged product of a token that already trades (the
// house's own exclusion rule — excluded categories, wrapped/staked names,
// exchange prefixes, version markers). On this snapshot that is 198 rows.
// Live-token protocols are kept apart and shown as comparables, at the market's
// own values, never mixed into the ranked board.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them. */
export interface ModelConstants {
  /** Comparables needed before a category earns its own multiple. */
  min_comps: number;
  /** Clamp on a category's median FDV/TVL multiple. */
  multiple_floor: number;
  multiple_cap: number;
  /** Growth: clamp on the 7-day change, and how much of it moves value. */
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  /** Maturity: floor and range over maturity_days. */
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  /** Chains: value added per extra chain, up to chain_cap extra chains. */
  chain_step: number;
  chain_cap: number;
}

export const MODEL: ModelConstants = {
  min_comps: 3,
  multiple_floor: 0.05,
  multiple_cap: 1.5,
  growth_weight: 0.6,
  growth_floor: -50,
  growth_cap: 100,
  maturity_floor: 0.7,
  maturity_range: 0.3,
  maturity_days: 1095,
  unknown_age_days: 365,
  chain_step: 0.03,
  chain_cap: 4,
};

